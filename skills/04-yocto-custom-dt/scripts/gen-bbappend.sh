#!/usr/bin/env bash
# Generate Yocto bbappend and directory structure for a custom DTS file
# Usage: gen-bbappend.sh <layer-dir> <dts-file> [machine]
#
# Example:
#   gen-bbappend.sh sources/meta-myboard k3-am625-myboard.dts am62xx-evm

set -euo pipefail

usage() {
    echo "Usage: $0 <layer-dir> <dts-file> [machine]"
    echo ""
    echo "  layer-dir  Path to your custom Yocto layer (e.g., sources/meta-myboard)"
    echo "  dts-file   DTS filename (e.g., k3-am625-myboard.dts)"
    echo "  machine    MACHINE name (default: am62xx-evm)"
    echo ""
    echo "Example:"
    echo "  $0 sources/meta-myboard k3-am625-myboard.dts am62xx-evm"
    exit 1
}

[[ $# -ge 2 ]] || usage

LAYER_DIR="$1"
DTS_FILE="$2"
MACHINE="${3:-am62xx-evm}"
DTB_FILE="${DTS_FILE%.dts}.dtb"
RECIPE_DIR="${LAYER_DIR}/recipes-kernel/linux"
FILES_DIR="${RECIPE_DIR}/files"
BBAPPEND="${RECIPE_DIR}/linux-ti-staging_%.bbappend"

echo "Generating bbappend for: ${DTS_FILE}"
echo "  Layer:   ${LAYER_DIR}"
echo "  Machine: ${MACHINE}"
echo "  Output:  ${BBAPPEND}"
echo ""

# Create directory structure
mkdir -p "${FILES_DIR}"

# Copy DTS file to layer if it exists locally
if [[ -f "${DTS_FILE}" ]]; then
    cp "${DTS_FILE}" "${FILES_DIR}/"
    echo "Copied ${DTS_FILE} to ${FILES_DIR}/"
elif [[ -f "board-support/ti-linux-kernel-"*"/arch/arm64/boot/dts/ti/${DTS_FILE}" ]]; then
    SRC=$(echo board-support/ti-linux-kernel-*/arch/arm64/boot/dts/ti/"${DTS_FILE}")
    cp "${SRC}" "${FILES_DIR}/"
    echo "Copied from kernel source: ${SRC}"
else
    echo "WARNING: ${DTS_FILE} not found locally — create ${FILES_DIR}/${DTS_FILE} manually"
    touch "${FILES_DIR}/${DTS_FILE}"
fi

# Generate bbappend file
cat > "${BBAPPEND}" << EOF
# Kernel bbappend for custom board DTS: ${DTS_FILE}
# Generated by gen-bbappend.sh

FILESEXTRAPATHS:prepend := "\${THISDIR}/files:"

# Add DTS file to source fetching
SRC_URI:append = " file://${DTS_FILE}"

# Copy DTS into kernel source tree before configuration
do_configure:append() {
    cp \${WORKDIR}/${DTS_FILE} \\
       \${S}/arch/arm64/boot/dts/ti/
}

# Add new DTB to the list of DTBs to build
KERNEL_DEVICETREE:append:${MACHINE} = " \\
    ti/${DTB_FILE} \\
"
EOF

echo "Created: ${BBAPPEND}"
echo ""
echo "Next steps:"
echo "  1. Edit ${FILES_DIR}/${DTS_FILE} to match your hardware"
echo "  2. Run: MACHINE=${MACHINE} bitbake linux-ti-staging"
echo "  3. Find DTB at: build/arago-tmp-default-glibc/deploy/images/${MACHINE}/${DTB_FILE}"
echo "  4. Copy DTB to SD boot partition and update extlinux.conf"
