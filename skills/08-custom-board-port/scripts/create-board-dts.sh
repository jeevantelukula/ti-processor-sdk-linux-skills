#!/usr/bin/env bash
# Generate a minimal custom board DTS for AM62x from the SK-AM62x reference
# Usage: create-board-dts.sh --name <board-name> --soc <am625|am623|am621>
#                            --kernel-src <path> [--output-dir <dir>]

set -euo pipefail

usage() {
    echo "Usage: $0 OPTIONS"
    echo ""
    echo "Options:"
    echo "  --name <board-name>     Your board name (e.g., my-am625-board)"
    echo "  --soc <am625|am623|am621>  Target SoC (default: am625)"
    echo "  --kernel-src <path>     Path to kernel source directory"
    echo "  --output-dir <dir>      Where to write DTS (default: current dir)"
    echo ""
    echo "Example:"
    echo "  $0 --name acme-am625-board --soc am625 \\"
    echo "     --kernel-src /opt/ti-sdk/board-support/ti-linux-kernel-6.18.38+gitAUTOINC"
    exit 1
}

BOARD_NAME=""
SOC="am625"
KERNEL_SRC=""
OUTPUT_DIR="$(pwd)"

while [[ $# -gt 0 ]]; do
    case "$1" in
        --name)        BOARD_NAME="$2"; shift 2 ;;
        --soc)         SOC="$2"; shift 2 ;;
        --kernel-src)  KERNEL_SRC="$2"; shift 2 ;;
        --output-dir)  OUTPUT_DIR="$2"; shift 2 ;;
        *) usage ;;
    esac
done

[[ -n "${BOARD_NAME}" ]] || { echo "ERROR: --name required"; usage; }
[[ -n "${KERNEL_SRC}" ]] || { echo "ERROR: --kernel-src required"; usage; }

# Validate SOC
case "${SOC}" in
    am625|am623|am621) ;;
    *) echo "ERROR: Unknown SoC '${SOC}'. Use am625, am623, or am621."; exit 1 ;;
esac

DT_DIR="${KERNEL_SRC}/arch/arm64/boot/dts/ti"
OUTPUT_FILE="${OUTPUT_DIR}/k3-${SOC}-${BOARD_NAME}.dts"

# Select reference DTS to copy from
REFERENCE_DTS="${DT_DIR}/k3-${SOC}-sk.dts"
if [[ ! -f "${REFERENCE_DTS}" ]]; then
    # Fallback: any matching SK DTS
    REFERENCE_DTS=$(find "${DT_DIR}" -name "k3-${SOC}*.dts" 2>/dev/null | head -1)
fi

if [[ -z "${REFERENCE_DTS}" || ! -f "${REFERENCE_DTS}" ]]; then
    echo "ERROR: Cannot find reference DTS for ${SOC} in ${DT_DIR}"
    echo "       Available DTS files:"
    ls "${DT_DIR}"/k3-*.dts 2>/dev/null | head -10
    exit 1
fi

echo "=== Creating Custom Board DTS ==="
echo "Board:     ${BOARD_NAME}"
echo "SoC:       ${SOC}"
echo "Reference: $(basename "${REFERENCE_DTS}")"
echo "Output:    ${OUTPUT_FILE}"
echo ""

# ── Generate DTS file ────────────────────────────────────────────────────────
cat > "${OUTPUT_FILE}" << DTSEOF
// SPDX-License-Identifier: GPL-2.0
/*
 * Custom board DTS for: ${BOARD_NAME}
 * Based on: $(basename "${REFERENCE_DTS}")
 * SoC: TI ${SOC^^}
 *
 * Generated by create-board-dts.sh - customize as needed.
 *
 * Steps after generation:
 *   1. Update model and compatible strings
 *   2. Add/remove peripherals to match your hardware
 *   3. Verify PADCONFIG offsets from SysConfig or TRM
 *   4. Test: make ARCH=arm64 CROSS_COMPILE=aarch64-oe-linux- dtbs
 */

/dts-v1/;

/* Include SoC base DTSI — provides all peripheral nodes disabled by default */
#include "k3-${SOC}.dtsi"

/ {
	model = "${BOARD_NAME^^} AM62x Board";
	compatible = "yourcompany,${BOARD_NAME}", "ti,${SOC}";

	chosen {
		stdout-path = "serial2:115200n8";
		/* serial2 = MAIN_UART0 — primary Linux console */
	};

	memory@80000000 {
		/* Update size to match your DRAM configuration:
		   0x80000000 for 2 GB, 0x40000000 for 1 GB */
		device_type = "memory";
		reg = <0x00000000 0x80000000 0x00000000 0x80000000>;
	};

	reserved-memory {
		#address-cells = <2>;
		#size-cells = <2>;
		ranges;

		/* Secure memory — required for OP-TEE (TF-A BL32) */
		secure_ddr: optee@9e800000 {
			reg = <0x00 0x9e800000 0x00 0x01800000>;
			alignment = <0x1000>;
			no-map;
		};

		/* MCU (M4F) RTOS memory — adjust if not using M4F */
		mcu_m4fss_dma_memory_region: m4f-dma-memory@9cb00000 {
			compatible = "shared-dma-pool";
			reg = <0x00 0x9cb00000 0x00 0x100000>;
			no-map;
		};

		mcu_m4fss_memory_region: m4f-memory@9cc00000 {
			compatible = "shared-dma-pool";
			reg = <0x00 0x9cc00000 0x00 0xe00000>;
			no-map;
		};
	};
};

/* ── MAIN UART0 (Linux console) ─────────────────────────────────────────── */
/* PADCONFIG offsets: find in SysConfig or grep existing DTS for UART0_RXD */
&main_pmx0 {
	main_uart0_pins_default: main-uart0-default-pins {
		pinctrl-single,pins = <
			/* Replace offsets with correct values from SysConfig / TRM */
			/* AM625_IOPAD(0x01c8, PIN_INPUT,  0) UART0_RXD */
			/* AM625_IOPAD(0x01cc, PIN_OUTPUT, 0) UART0_TXD */
		>;
	};
};

&main_uart0 {
	pinctrl-names = "default";
	pinctrl-0 = <&main_uart0_pins_default>;
	status = "okay";
};

/* ── I2C0 (PMIC / board management — adjust if present) ─────────────────── */
&main_i2c0 {
	pinctrl-names = "default";
	/* pinctrl-0 = <&main_i2c0_pins_default>; */
	clock-frequency = <400000>;
	status = "disabled"; /* Enable when I2C pins are configured */
};

/* ── SPI0 (flash or external device — adjust if present) ────────────────── */
&main_spi0 {
	/* pinctrl-0 = <&main_spi0_pins_default>; */
	status = "disabled";
};

/* ── eMMC (SDHCI0) — enable if your board has eMMC ─────────────────────── */
&sdhci0 {
	/* For eMMC: keep as-is from reference DTS */
	status = "disabled";
};

/* ── SD Card (SDHCI1) — enable if your board has SD slot ───────────────── */
&sdhci1 {
	/* For SD: add cd-gpios if using card detect GPIO */
	status = "disabled";
};

/* ── Ethernet — enable if your board has Ethernet ──────────────────────── */
/* CPSW3G is a 2-port ethernet switch; use only port 1 for single-PHY boards */
&cpsw3g {
	status = "disabled";
};

/* ── USB ────────────────────────────────────────────────────────────────── */
&usbss0 {
	status = "disabled";
};

/* ── M4F remoteproc — keep enabled if using R5/M4 RTOS cores ───────────── */
&mcu_m4fss {
	mboxes = <&mailbox0_cluster0 &mbox_m4_0>;
	memory-region = <&mcu_m4fss_dma_memory_region>,
	                <&mcu_m4fss_memory_region>;
	status = "okay";
};

/*
 * HOW TO ADD A GPIO:
 * 1. Find PADCONFIG offset from SysConfig or TRM
 * 2. Add to &main_pmx0:
 *      my_gpio_pins: my-gpio-pins {
 *          pinctrl-single,pins = <
 *              AM625_IOPAD(0x01c0, PIN_INPUT, 7)  // GPIO0_xx
 *          >;
 *      };
 * 3. Add consumer node (e.g. gpio-leds, gpio-keys, or custom node)
 * 4. Rebuild DTB and test with gpiodetect + gpioget on target
 *
 * PIN_INPUT  = 0x00050000 (RXACTIVE=1, PULLUDDIS=1) — required for input reads
 * PIN_OUTPUT = 0x00000000 (RXACTIVE=0) — DO NOT use PIN_OUTPUT for gpios you read
 */
DTSEOF

echo "DTS created: ${OUTPUT_FILE}"
echo ""
echo "Next steps:"
echo "  1. Edit ${OUTPUT_FILE} to match your hardware"
echo "  2. Add correct PADCONFIG offsets from SysConfig (ti.com/tool/SYSCONFIG)"
echo "  3. Enable/disable peripheral nodes as needed"
echo "  4. Test compile:"
echo "     make -C ${KERNEL_SRC} ARCH=arm64 \\"
echo "       CROSS_COMPILE=aarch64-oe-linux- \\"
echo "       DTC_FLAGS='-@' \\"
echo "       arch/arm64/boot/dts/ti/k3-${SOC}-${BOARD_NAME}.dtb"
echo "  5. To add to Yocto, use skill 04-yocto-custom-dt"
